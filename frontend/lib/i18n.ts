export type TranslationKey = keyof typeof translations.en;

export function translate(language: UILanguage, key: TranslationKey): string {
  return translations[language][key] ?? translations.en[key];
}

/** Reads the persisted UI language and returns a `t(key)` translator bound to it. */
export function useT() {
  const language = useAppStore((s) => s.uiLanguage);
  return { language, t: (key: TranslationKey) => translate(language, key) };
}
